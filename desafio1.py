# Código funcional: Soma de dois números
# Entrada do primeiro número pelo usuário
num1 = float(input("Digite o primeiro número: "))
# Entrada do segundo número pelo usuário
num2 = float(input("Digite o segundo número: "))
# Cálculo da soma dos dois números
soma = num1 + num2
# Saída do resultado na tela
print("A soma de", num1, "e", num2, "é igual a", soma)
